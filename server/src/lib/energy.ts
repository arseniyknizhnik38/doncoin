/**
 * Сколько энергии стоит один тап.
 *
 * Энергия хранится в базе целым числом, а игре нужен медленный реген:
 * обойма должна копиться около часа, иначе игрок выжимает всё за один
 * присест и ему незачем возвращаться. Один тап в секунду давал бы полную
 * обойму за пятнадцать минут, а дробное восстановление в Int не положишь —
 * поэтому единицей стал не тап, а десятая его часть.
 *
 * Отсюда: реген «1 в секунду» — это 6 тапов в минуту, а обойма в 600 тапов
 * копится 100 минут.
 *
 * Константа лежит в отдельном файле, потому что нужна и улучшениям,
 * и начислению тапов, а те друг о друге знать не должны.
 */
export const ENERGY_PER_TAP = 10;
