import type { User } from '../generated/prisma/client.js';
import { activeIncomePerHour } from './rewards.js';

/**
 * Конверт — единственная награда в игре, размер которой заранее неизвестен.
 *
 * Всё остальное здесь считается до монеты: бонус дня, задания, шифр, доход
 * бизнесов. Предсказуемая награда перестаёт радовать примерно на третий раз —
 * её начинают просто забирать. Непредсказуемая не перестаёт, потому что
 * проверить, что внутри, можно только открыв.
 *
 * Ради этого конверт и заведён: в игре не было ни одной случайной величины.
 *
 * Заносят с ранга «Солдат» — раньше игрок ещё не свой, ему не заносят. Это
 * не только по смыслу: первые два-три дня в игре и так не скучно, новизна
 * работает сама. Скучно становится ровно там, где она кончается, и конверт
 * приходит в этот момент.
 */

/** С какой ступени ранга начинают заносить. */
export const ENVELOPE_FROM_STEP = 6;

export interface EnvelopeTier {
  id: string;
  title: string;
  /** Доля случаев, сумма всех долей — единица. */
  chance: number;
  /** Награда в часах активного дохода игрока. */
  hours: number;
}

/**
 * Раскладка. Средняя выплата — около двух с половиной часов дохода в сутки,
 * сопоставимо с ежедневным бонусом: конверт добавляет азарт, а не ломает
 * экономику.
 *
 * Верхняя ступень выпадает примерно раз в месяц на игрока. Реже делать
 * нельзя: о награде, которой никто не видел, не говорят, а весь смысл
 * крупного выигрыша в том, что о нём рассказывают.
 */
export const ENVELOPE_TIERS: readonly EnvelopeTier[] = [
  { id: 'thin', title: 'Тонкий конверт', chance: 0.6, hours: 1 },
  { id: 'usual', title: 'Обычный конверт', chance: 0.25, hours: 2.5 },
  { id: 'thick', title: 'Плотный конверт', chance: 0.12, hours: 6 },
  { id: 'fat', title: 'Толстый конверт', chance: 0.03, hours: 20 },
];

/**
 * Выбирает ступень по броску от 0 до 1.
 *
 * Вынесено отдельной чистой функцией, чтобы раскладку можно было проверить
 * тестом: у случайности легко ошибиться на границе и незаметно раздавать
 * верхнюю ступень вдесятеро чаще задуманного.
 */
export function pickTier(roll: number): EnvelopeTier {
  let passed = 0;

  for (const tier of ENVELOPE_TIERS) {
    passed += tier.chance;

    if (roll < passed) {
      return tier;
    }
  }

  // Бросок ровно 1 или накопленная погрешность долей — отдаём последнюю.
  return ENVELOPE_TIERS[ENVELOPE_TIERS.length - 1]!;
}

/** Сколько монет в конверте этой ступени для конкретного игрока. */
export function envelopeReward(
  tier: EnvelopeTier,
  user: Pick<User, 'coinsPerTap' | 'energyPerSecond'>,
): bigint {
  return BigInt(Math.floor(activeIncomePerHour(user) * tier.hours));
}

/** Средняя выплата в часах дохода — для проверки баланса. */
export function averageHours(): number {
  return ENVELOPE_TIERS.reduce((sum, tier) => sum + tier.chance * tier.hours, 0);
}
