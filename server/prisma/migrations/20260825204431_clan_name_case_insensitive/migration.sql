-- Уникальность названия клана без учёта регистра.
-- Обычный UNIQUE в Postgres регистрозависим, поэтому «Корлеоне» и «корлеоне»
-- считались бы разными кланами. Функциональный индекс закрывает это на уровне
-- базы, а не только проверкой в коде — значит и гонка двух одновременных
-- созданий не пройдёт.

CREATE UNIQUE INDEX "Clan_name_lower_key" ON "Clan" (lower("name"));
